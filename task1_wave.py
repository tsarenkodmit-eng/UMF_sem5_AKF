#!/usr/bin/env python3
"""Task 1: spherical pressure wave in an infinite isotropic elastic medium.

The code solves the radial displacement equation using second-order centered
finite differences and compares it with the outgoing-wave analytical solution.
Run from any directory, e.g.:
    python task1_wave.py --output-dir results
Dependencies: NumPy and Matplotlib.
"""
from __future__ import annotations

import argparse
import csv
import math
from pathlib import Path
from typing import NamedTuple

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import numpy.typing as npt

FloatArray = npt.NDArray[np.float64]


class Parameters(NamedTuple):
    young_modulus: float = 5.4e9      # Pa
    shear_modulus: float = 2.0e9      # Pa (mu)
    density: float = 1800.0           # kg/m^3
    cavity_radius: float = 1.0        # m
    pressure: float = 1.0e8           # Pa
    final_time: float = 0.01          # s
    h_over_R: float = 0.01
    outer_margin_in_h: int = 100


def material_constants(p: Parameters) -> dict[str, float]:
    """Recover Lamé's first parameter and P-wave speed from E, mu and rho."""
    if p.young_modulus <= 0 or p.shear_modulus <= 0 or p.density <= 0:
        raise ValueError("E, mu and rho must be positive.")
    nu = p.young_modulus / (2.0 * p.shear_modulus) - 1.0
    if not (-1.0 < nu < 0.5):
        raise ValueError(f"The inferred Poisson ratio is not physical: nu={nu}.")
    lam = 2.0 * p.shear_modulus * nu / (1.0 - 2.0 * nu)
    bulk_longitudinal = lam + 2.0 * p.shear_modulus
    cp = math.sqrt(bulk_longitudinal / p.density)
    return {"nu": nu, "lambda": lam, "K": bulk_longitudinal, "cp": cp}


def analytic_displacement(r: FloatArray, t: float, p: Parameters,
                          constants: dict[str, float]) -> FloatArray:
    """Exact outgoing radial displacement generated by a step pressure."""
    mu = p.shear_modulus
    rho = p.density
    R = p.cavity_radius
    P0 = p.pressure
    cp = constants["cp"]

    a = 4.0 * mu / (rho * cp * R)
    b = 4.0 * mu / (rho * R**2)
    omega_sq = b - 0.25 * a**2
    if omega_sq <= 0:
        raise ValueError("Analytical expression expects positive omega^2.")
    omega = math.sqrt(omega_sq)
    beta = 0.5 * a
    B_inf = P0 * R**3 / (4.0 * mu)

    # s is the retarded time measured from the pressure step at the cavity wall.
    s = t - (r - R) / cp
    B = np.zeros_like(r, dtype=float)
    B_prime = np.zeros_like(r, dtype=float)
    active = s >= 0.0
    sa = s[active]
    decay = np.exp(-beta * sa)
    B[active] = B_inf * (
        1.0 - decay * (np.cos(omega * sa) + (beta / omega) * np.sin(omega * sa))
    )
    B_prime[active] = (P0 * R / (rho * omega)) * decay * np.sin(omega * sa)
    return B_prime / (cp * r) + B / r**2


def solve_finite_differences(p: Parameters) -> tuple[FloatArray, FloatArray, dict[str, float]]:
    """Explicit second-order FD solution at the requested final time.

    The internal-pressure condition is imposed with a second-order centered
    derivative and a ghost point at r=R. The outer boundary is placed beyond
    the wavefront so it cannot influence the requested time interval.
    """
    c = material_constants(p)
    cp, lam, K = c["cp"], c["lambda"], c["K"]
    mu, rho, R, P0 = p.shear_modulus, p.density, p.cavity_radius, p.pressure
    h = p.h_over_R * R
    dt = h / cp  # prescribed Courant number C = cp*dt/h = 1

    # Put the fixed outer boundary a positive margin beyond the target wavefront.
    n_intervals = int(math.ceil(cp * p.final_time / h)) + p.outer_margin_in_h
    r = R + h * np.arange(n_intervals + 1, dtype=float)
    nt = int(math.ceil(p.final_time / dt))

    def spatial_operator(u: FloatArray, pressure_now: float) -> FloatArray:
        """Second-order approximation of u_rr + 2*u_r/r - 2*u/r^2."""
        L = np.zeros_like(u)
        # Stress at r=R: K*u_r + 2*lambda*u/R = -p.
        # With u_r=(u_1-u_-1)/(2h), solve for the ghost value u_-1.
        u_ghost = u[1] + (2.0 * h / K) * (pressure_now + 2.0 * lam * u[0] / R)
        L[0] = (
            (u[1] - 2.0 * u[0] + u_ghost) / h**2
            + (u[1] - u_ghost) / (R * h)
            - 2.0 * u[0] / R**2
        )
        ri = r[1:-1]
        L[1:-1] = (
            (u[2:] - 2.0 * u[1:-1] + u[:-2]) / h**2
            + (u[2:] - u[:-2]) / (ri * h)
            - 2.0 * u[1:-1] / ri**2
        )
        # The boundary is causally untouched before the target time.
        L[-1] = 0.0
        return L

    # Initial conditions: u(r,0)=0 and u_t(r,0)=0.
    u0 = np.zeros_like(r)
    # Second-order startup using the right-hand limit of the pressure step.
    u1 = u0 + 0.5 * dt**2 * cp**2 * spatial_operator(u0, P0)
    u1[-1] = 0.0
    previous, current = u0, u1

    for _n in range(1, nt):
        L = spatial_operator(current, P0)
        following = 2.0 * current - previous + dt**2 * cp**2 * L
        following[-1] = 0.0
        previous, current = current, following
        if not np.isfinite(current).all():
            raise FloatingPointError("Non-finite value encountered in FD solution.")

    # target time generally does not coincide with t_n; interpolate between
    # adjacent second-order time levels to report exactly t = final_time.
    t_lo = (nt - 1) * dt
    alpha = (p.final_time - t_lo) / dt
    u_at_target = (1.0 - alpha) * previous + alpha * current
    diagnostics = {
        **c,
        "h": h,
        "dt": dt,
        "courant": cp * dt / h,
        "n_intervals": float(n_intervals),
        "n_time_steps": float(nt),
        "last_stored_time": nt * dt,
        "interpolation_alpha": alpha,
        "outer_radius": float(r[-1]),
        "wavefront_radius": R + cp * p.final_time,
    }
    return r, u_at_target, diagnostics


def write_outputs(output_dir: Path, p: Parameters) -> dict[str, float]:
    output_dir.mkdir(parents=True, exist_ok=True)
    c = material_constants(p)
    r, u_fd, diagnostics = solve_finite_differences(p)
    u_exact = analytic_displacement(r, p.final_time, p, c)
    absolute_error = np.abs(u_fd - u_exact)
    inside_wavefront = r <= diagnostics["wavefront_radius"] + 1e-12
    max_exact = float(np.max(np.abs(u_exact[inside_wavefront])))
    max_abs_error = float(np.max(absolute_error[inside_wavefront]))
    rel_error = max_abs_error / max_exact if max_exact else math.nan
    diagnostics["max_abs_error_m"] = max_abs_error
    diagnostics["relative_max_error"] = rel_error
    diagnostics["max_exact_displacement_m"] = max_exact

    csv_path = output_dir / "task1_profile_t001.csv"
    with csv_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        writer.writerow(["r_m", "u_finite_difference_m", "u_analytic_m", "abs_error_m"])
        writer.writerows(zip(r, u_fd, u_exact, absolute_error))

    fig, axes = plt.subplots(1, 2, figsize=(12.4, 4.8), constrained_layout=True)
    mm = 1e3
    axes[0].plot(r, mm * u_exact, lw=2.1, label="Аналитическое решение")
    axes[0].plot(r, mm * u_fd, "--", lw=1.35, label="МКР, второй порядок")
    axes[0].axvline(diagnostics["wavefront_radius"], color="0.4", lw=1.0,
                    ls=":", label="Фронт волны")
    axes[0].set_xlim(p.cavity_radius, diagnostics["outer_radius"])
    axes[0].set_xlabel("r, м")
    axes[0].set_ylabel("u(r, t*), мм")
    axes[0].set_title("Распределение перемещения")
    axes[0].grid(True, alpha=0.25)
    axes[0].legend(fontsize=8, loc="upper right")

    zoom_left = max(p.cavity_radius, diagnostics["wavefront_radius"] - 8.0)
    zoom_right = diagnostics["wavefront_radius"] + 0.4
    zoom = (r >= zoom_left) & (r <= zoom_right)
    axes[1].plot(r[zoom], mm * u_exact[zoom], lw=2.1, label="Аналитическое решение")
    axes[1].plot(r[zoom], mm * u_fd[zoom], "--", lw=1.35, label="МКР, второй порядок")
    axes[1].axvline(diagnostics["wavefront_radius"], color="0.4", lw=1.0, ls=":")
    axes[1].set_xlabel("r, м")
    axes[1].set_ylabel("u(r, t*), мм")
    axes[1].set_title("Фронт и переходная область")
    axes[1].grid(True, alpha=0.25)
    axes[1].legend(fontsize=8, loc="best")

    fig.savefig(output_dir / "task1_displacement.png", dpi=200)
    fig.savefig(output_dir / "task1_displacement.svg")
    plt.close(fig)

    report_path = output_dir / "task1_diagnostics.txt"
    report_path.write_text(
        "Task 1: spherical cavity under step pressure\n"
        + "\n".join(f"{key} = {value:.12g}" for key, value in diagnostics.items())
        + "\n",
        encoding="utf-8",
    )
    return diagnostics


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=Path("results"),
                        help="directory for CSV, plot and diagnostics (default: results)")
    args = parser.parse_args()
    diagnostics = write_outputs(args.output_dir, Parameters())
    for key, value in diagnostics.items():
        print(f"{key}: {value:.12g}")
    print(f"Outputs written to: {args.output_dir.resolve()}")


if __name__ == "__main__":
    main()
